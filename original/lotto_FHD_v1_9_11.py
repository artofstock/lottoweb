#  │  sound_on   : 소리 ON/OFF 상태      (기본 True)                         │
#  │  auto_play  : 자동 진행 ON/OFF      (기본 False)                        │
#  └─────────────────────────────────────────────────────────────────────────┘
#  프로그램 종료 시 자동 저장, 다음 실행 시 자동 로드한다.
# ══════════════════════════════════════════════════════════════════════════════
class LottoConfig:
    """JSON 설정 파일 저장·로드 전담."""

    # v1.9.0: APP_DIR 기준 절대경로 — 다른 폴더에서 실행해도 설정 공유
    CONFIG_FILE = os.path.join(APP_DIR, 'lotto_config.json')

    # 기본값 (설정 파일이 없을 때 사용)
    DEFAULTS: Dict = {
        'round':        1217,
        'round_suffix': '',
        'max_games':    100,
        'sound_on':     True,
        'auto_play':    False,
        'tts_on':       False,    # v1.8: TTS 음성안내 (기본 OFF — 첫 사용 시 사용자가 켬)
        'hole_count':   1,        # v1.9.1: 구멍 개수 (1 또는 4, 기본 1=기존 동작)
    }

    def __init__(self):
        self._data: Dict = dict(self.DEFAULTS)
        self.load()

    # ── 로드 ──────────────────────────────────────────────────────────────────
    def load(self):
        """config.json을 읽어 설정을 복원한다. 파일이 없으면 기본값 유지."""
        # v1.9.6: 모듈 레벨 json import 사용 (재import 제거)
        try:
            with open(self.CONFIG_FILE, 'r', encoding='utf-8') as f:
                saved = json.load(f)
            # 저장된 키만 병합 (새 기본값 키는 DEFAULTS에서 유지)
            for k, v in saved.items():
                if k in self.DEFAULTS:
                    self._data[k] = v
            log.info(f"설정 로드: {self.CONFIG_FILE}  {self._data}")
        except FileNotFoundError:
            log.debug("설정 파일 없음 → 기본값 사용")
        except Exception as e:
            log.warning(f"설정 로드 실패 ({e}) → 기본값 사용")

    # ── 저장 ──────────────────────────────────────────────────────────────────
    def save(self):
        """현재 설정을 config.json에 저장한다."""
        # v1.9.6: 모듈 레벨 json import 사용
        try:
            with open(self.CONFIG_FILE, 'w', encoding='utf-8') as f:
                json.dump(self._data, f, ensure_ascii=False, indent=2)
            log.debug(f"설정 저장: {self._data}")
        except Exception as e:
            log.warning(f"설정 저장 실패: {e}")

    # ── 접근자 ────────────────────────────────────────────────────────────────
    @property
    def round(self)        -> int:  return int(self._data['round'])
    @property
    def round_suffix(self) -> str:
        """v1.9.0: 캡슐화 — 외부에서 _data 직접 접근하지 않도록 노출"""
        return str(self._data.get('round_suffix', ''))
    @property
    def max_games(self)    -> int:  return int(self._data['max_games'])
    @property
    def sound_on(self)     -> bool: return bool(self._data['sound_on'])
    @property
    def auto_play(self)    -> bool: return bool(self._data['auto_play'])
    @property
    def tts_on(self)       -> bool: return bool(self._data.get('tts_on', False))
    @property
    def hole_count(self)   -> int:
        """v1.9.1: 구멍 개수 (1, 2, 또는 4). 잘못된 값은 1로 강제.
        v1.9.2: 2구멍 모드(대각선 대칭) 추가 — 허용값 확장."""
        v = int(self._data.get('hole_count', 1))
        return v if v in (1, 2, 4) else 1

    def set(self, key: str, value):
        if key in self.DEFAULTS:
            self._data[key] = value


