    def toggle_tts(self) -> bool:
        """TTS ON/OFF 시각 갱신. 실제 동작은 LottoMachine에서 처리."""
        self._tts_on = not getattr(self, '_tts_on', False)
        if self._tts_on:
            # ON — 수희 아이콘 강조 (분홍/금색 톤)
            self.tts_btn.config(text="🎙", fg='#FFB7D5', bg='#3a1a3a')
        else:
            self.tts_btn.config(text="🎙", fg='#556677', bg='#0d1b2a')
        return self._tts_on

    def set_tts_state(self, enabled: bool, available: bool = True):
        """TTS 시각 상태를 강제 설정 (앱 시작 시 저장된 설정 복원용)."""
        self._tts_on = bool(enabled) and available
        if not available:
            # 백엔드 미사용 시 비활성 상태로 표시
            self.tts_btn.config(text="🎙", fg='#33404e', bg='#0a1424',
                                state='disabled')
        elif self._tts_on:
            self.tts_btn.config(text="🎙", fg='#FFB7D5', bg='#3a1a3a')
        else:
            self.tts_btn.config(text="🎙", fg='#556677', bg='#0d1b2a')

    @property
    def tts_on(self) -> bool:
        return getattr(self, '_tts_on', False)

    # ── v1.9.1: 구멍 개수 토글 시각 갱신 (v1.9.2: 2구멍 색상 추가) ──────────
    def set_hole_count_visual(self, count: int):
        """1·2·4 구멍 모드의 버튼 시각 갱신 + 캔버스 구멍 가시성 동기화.

        실제 엔진 변경은 LottoMachine에서 처리, 여기는 UI만.
          count=1 → 🎯1 (시안 톤,  기본/느린 페이스)
          count=2 → 🎯2 (오렌지 톤, 중간 페이스)
          count=4 → 🎯4 (골드 톤,   빠른 페이스)
        """
        if count not in (1, 2, 4):
            count = 1
        if count == 4:
            self.hole_btn.config(text="🎯4", fg='#FFD700', bg='#3a2a0a')
        elif count == 2:
            self.hole_btn.config(text="🎯2", fg='#FFA552', bg='#3a2410')
        else:
            self.hole_btn.config(text="🎯1", fg='#7fc8ff', bg='#1a3a5a')
        # 캔버스 구멍 가시성 동기화
        self.apply_hole_count_visual(count)


