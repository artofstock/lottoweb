class LottoMachine:
    """컨트롤러: LottoEngine · LottoStorage · LottoUI를 조율한다."""

    def __init__(self, root: tk.Tk):
        self.root    = root
        self.config  = LottoConfig()   # 설정 자동 로드 (먼저!)
        # v1.9.1: 엔진은 config에서 hole_count 받아 초기화
        self.engine  = LottoEngine(hole_count=self.config.hole_count)
        self.storage = LottoStorage()

        # 설정값 → 엔진·스토리지에 반영
        # v1.9.7 ⚠️ round_suffix 도 반드시 create_new_file() 이전에 설정!
        # 기존 버그: suffix가 create_new_file 이후 설정되어 첫 파일에 부제 빠짐
        self.engine.max_games     = self.config.max_games
        self.storage.round        = self.config.round
        self.storage.round_suffix = self.config.round_suffix

        # ── 상태 머신 ────────────────────────────────────────────────────────
        # v1.7: _max_games_reached bool 제거 → GameState.COMPLETED로 통합
        self._sm               = _StateMachine()
        self.auto_timer        = None
        self.auto_countdown    = 0
        self.accel_timer       = None

        # UI 생성 – 버튼 콜백을 여기서 주입 (v1.9.0: switch_tab 제거)
        self.ui = LottoUI(root, {
            'start':             self.start_draw,
            'reset':             self.reset,
            'sound_toggle':      self._toggle_sound,
            'tts_toggle':        self._toggle_tts,        # v1.8
            'hole_toggle':       self._toggle_hole_count, # v1.9.1
            'clear_history':     self.ui_clear_history,
            'change_round':      self._open_round_dialog,
            'auto_changed':      self._on_auto_changed,
            'max_games_changed': self._on_max_games_changed,
        })

        # v1.9.7: 이제 round_suffix가 이미 설정됨 — 첫 파일부터 부제 포함
        self.storage.create_new_file()
        self.ui.update_round(self.storage.round, self.storage.round_suffix)
        # 저장된 설정값 복원
        if not self.config.sound_on:
            self.ui.toggle_sound()
            _sound_engine.set_enabled(False)
        if self.config.auto_play:
            self.ui.auto_var.set(True)
        # v1.8: TTS 상태 복원 — 백엔드 사용 가능 여부 + 사용자 설정
        tts_avail = _tts_engine.available
        tts_want  = self.config.tts_on and tts_avail
        _tts_engine.set_enabled(tts_want)
        self.ui.set_tts_state(enabled=tts_want, available=tts_avail)
        if not tts_avail:
            log.info("TTS 백엔드 미사용 — 버튼 비활성 처리됨")
        # v1.9.1: 구멍 개수 시각 복원 (엔진은 생성자에서 이미 적용됨)
        self.ui.set_hole_count_visual(self.config.hole_count)
