# 5.  LottoStorage  –  파일 저장/로드 (tkinter 없음)
# ══════════════════════════════════════════════════════════════════════════════
class LottoStorage:
    """결과 파일 생성·저장·로드 전담."""

    DEFAULT_ROUND = 1217   # 기본 회차 (실행 시 다이얼로그에서 변경 가능)

    # v1.8: 파일명에 사용 불가한 문자 (Windows·Unix 양쪽 안전)
    _UNSAFE_CHARS = '\\/:*?"<>|\t\n\r'

    @classmethod
    def _sanitize_suffix(cls, suffix: str) -> str:
        """부제를 파일명 안전 문자열로 변환.
        - 금지문자 제거
        - 앞뒤 공백 제거
        - 내부 공백을 _ 로 치환
        - 결과가 빈 문자열이면 "" 반환
        """
        if not suffix:
            return ""
        s = suffix
        for ch in cls._UNSAFE_CHARS:
            s = s.replace(ch, '')
        s = s.strip().replace(' ', '_')
        return s

    def __init__(self, round_no: int = DEFAULT_ROUND):
        self.round        = round_no
        self.round_suffix = ''
        self.file_path: Optional[str] = None

    def create_new_file(self) -> str:
        """새 결과 파일을 만들고 경로를 반환한다.

        v1.8: 부제가 있으면 파일명에 포함
          · 부제 있음: lotto_{round}_{suffix}_result_{datetime}.txt
          · 부제 없음: lotto_{round}_result_{datetime}.txt          (기존)
        """
        now = datetime.now().strftime("%Y%m%d%H%M")
        safe_suffix = self._sanitize_suffix(self.round_suffix)
        suffix_part = f"_{safe_suffix}" if safe_suffix else ""
        fname = f"lotto_{self.round}{suffix_part}_result_{now}.txt"
        # v1.9.0: APP_DIR 기준 — 다른 폴더에서 실행해도 결과 한 곳에 모임
        self.file_path = os.path.join(APP_DIR, fname)

        # 파일 헤더에도 부제 표기
        header_suffix = f" {self.round_suffix}" if self.round_suffix else ""
        with open(self.file_path, 'w', encoding='utf-8') as f:
            f.write(f"# 로또 {self.round}회{header_suffix} 예상번호 추첨 결과\n")
        log.info(f"새 결과 파일 생성: {fname}")
        return self.file_path

    def save_result(self, numbers: List[int]):
        """오름차순 번호 6개를 파일에 한 줄 추가한다."""
        if len(numbers) != 6 or not self.file_path:
            return
        try:
            with open(self.file_path, 'a', encoding='utf-8') as f:
                f.write("\t".join(map(str, numbers)) + "\n")
        except Exception as e:
            log.error(f"결과 파일 저장 실패: {e}  numbers={numbers}")

    # ── v1.9.10: 엑셀(.xlsx) 자동 생성 ───────────────────────────────────────
    # txt 결과 파일에 새 줄이 추가될 때마다 호출된다. lotto_template.xlsx 서식을
    # 불러와 3개 시트(Sheet2 (2) / total / Sheet1)의 데이터만 최신 결과로
    # 갱신한 뒤, txt 와 같은 이름의 .xlsx 로 저장한다(서식·차트는 템플릿 그대로 유지).
    def _read_games(self) -> List[List[int]]:
        """현재 결과 txt 파일을 읽어 회차별 6개 번호 리스트로 반환한다."""
        games: List[List[int]] = []
        if not self.file_path or not os.path.exists(self.file_path):
            return games
        try:
            with open(self.file_path, 'r', encoding='utf-8') as f:
                for line in f:
                    line = line.strip()
                    if not line or line.startswith('#'):
                        continue
                    parts = [p for p in line.split('\t') if p.strip()]
                    if len(parts) != 6:
                        continue
                    try:
                        games.append([int(p) for p in parts])
                    except ValueError:
                        continue
        except Exception as e:
            log.error(f"결과 txt 읽기 실패(엑셀 생성용): {e}")
        return games

    def export_excel(self):
        """lotto_template.xlsx 서식을 기반으로 결과 .xlsx 파일을 (재)생성한다.
        openpyxl 미설치 또는 템플릿 파일 부재 시 조용히 건너뛴다."""
        if not _OPENPYXL_OK:
            return None
        if not self.file_path:
            return None
        if not os.path.exists(EXCEL_TEMPLATE_PATH):
            log.debug(f"엑셀 템플릿 없음({EXCEL_TEMPLATE_PATH}) → 엑셀 생성 건너뜀")
            return None

        games = self._read_games()
        if not games:
            return None

        freq: Dict[int, int] = {n: 0 for n in range(1, 46)}
        for nums in games:
            for n in nums:
                if 1 <= n <= 45:
                    freq[n] += 1
        total_picks = len(games) * 6
        ranked = sorted(freq.items(), key=lambda x: (-x[1], x[0]))

        try:
            wb = load_workbook(EXCEL_TEMPLATE_PATH)
        except Exception as e:
            log.error(f"엑셀 템플릿 열기 실패: {e}")
            return None

        try:
            # ── Sheet2 (2): 회차별 원본 번호 (기존 내용 지우고 새로 기록) ──────
            if "Sheet2 (2)" in wb.sheetnames:
                ws_raw = wb["Sheet2 (2)"]
                # v1.9.11 수정: 폰트 크기가 안 맞던 문제 — 기존엔 Font(size=11)을
                # 새로 만들어 덮어썼는데, 실제 템플릿은 32pt·볼드였음. 하드코딩 대신
                # 템플릿 1행에 이미 적용된 폰트/정렬을 그대로 읽어와 재사용한다.
                idx_font = copy.copy(ws_raw.cell(row=1, column=1).font)
                num_font = copy.copy(ws_raw.cell(row=1, column=2).font)
                center   = copy.copy(ws_raw.cell(row=1, column=1).alignment)
                max_row  = max(ws_raw.max_row, len(games))
                for r in range(1, max_row + 1):
                    if r <= len(games):
                        nums = games[r - 1]
                        c = ws_raw.cell(row=r, column=1, value=str(r))
                        c.font = idx_font; c.alignment = center
                        for j, n in enumerate(nums):
                            c = ws_raw.cell(row=r, column=2 + j, value=n)
                            c.font = num_font; c.alignment = center
                    else:
                        # cell(value=None)은 openpyxl에서 no-op이므로 .value에 직접 대입
                        for col in range(1, 8):
                            ws_raw.cell(row=r, column=col).value = None

            # ── Sheet1: 1~45번 전체 출현 빈도 내림차순 (A/B만 갱신, C 수식 유지) ─
            if "Sheet1" in wb.sheetnames:
                ws_rank = wb["Sheet1"]
                for r, (num, cnt) in enumerate(ranked, start=1):
                    pct = (cnt / total_picks) if total_picks else 0
                    ws_rank.cell(row=r, column=1, value=num)
                    ws_rank.cell(row=r, column=2, value=f"{pct * 100:.1f}%")

            # ── total: 번호별 빈도 막대그래프용 데이터 (C/D만 갱신) ────────────
            if "total" in wb.sheetnames:
                ws_total = wb["total"]
                for r, (num, cnt) in enumerate(ranked, start=2):
                    pct = (cnt / total_picks) if total_picks else 0
                    ws_total.cell(row=r, column=3, value=num)
                    ws_total.cell(row=r, column=4, value=round(pct, 4))

            xlsx_path = os.path.splitext(self.file_path)[0] + ".xlsx"
            wb.save(xlsx_path)
            log.info(f"엑셀 결과 파일 자동 생성: {os.path.basename(xlsx_path)}")
            return xlsx_path
        except Exception as e:
            log.error(f"엑셀 생성 실패: {e}")
            return None


