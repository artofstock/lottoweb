# ── 로깅 설정 ─────────────────────────────────────────────────────────────────
#  콘솔: INFO 이상 / 파일: DEBUG 이상 (lotto_app.log)
#  게임 실행 이력, 예외, 백엔드 선택 결과 등을 기록한다.
def _setup_logging() -> logging.Logger:
    logger = logging.getLogger('LottoApp')
    logger.setLevel(logging.DEBUG)

    fmt = logging.Formatter(
        '%(asctime)s [%(levelname)s] %(message)s',
        datefmt='%H:%M:%S',
    )

    # 콘솔 핸들러 (INFO 이상)
    ch = logging.StreamHandler()
    ch.setLevel(logging.INFO)
    ch.setFormatter(fmt)

    # 파일 핸들러 (DEBUG 이상, 최대 500KB × 2개 롤링)
    # v1.9.0: APP_DIR 기준 절대경로 — 다른 폴더에서 실행해도 로그 통합
    try:
        from logging.handlers import RotatingFileHandler
        log_path = os.path.join(APP_DIR, 'lotto_app.log')
        fh = RotatingFileHandler(
            log_path, maxBytes=500_000, backupCount=2,
            encoding='utf-8',
        )
        fh.setLevel(logging.DEBUG)
        fh.setFormatter(fmt)
        logger.addHandler(fh)
    except Exception:
        pass   # 파일 쓰기 권한 없으면 콘솔만 사용

    logger.addHandler(ch)
    return logger

log = _setup_logging()

