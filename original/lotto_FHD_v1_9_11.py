        row.pack(fill=tk.X)
        tk.Frame(row, height=1, bg='#1a2a3a').pack(fill=tk.X)   # 1px 세선
        inner = tk.Frame(row, bg=row_bg)
        inner.pack(fill=tk.X, padx=padx, pady=pady)
