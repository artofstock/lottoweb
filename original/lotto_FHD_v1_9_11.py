    @staticmethod
    def _make_badge(parent: tk.Widget, number: int,
                    bg: str, size: int = 32,
                    active: bool = True,
                    font_size: int = 11,
                    padx: int = 2) -> tk.Canvas:
        """
        번호가 적힌 작은 원형 공 배지를 생성하고 pack 한다.

        active=False → 회색 처리 (비어 있는 빈도 슬롯용)
        """
        c       = ball_color(number) if active else '#2a3a4a'
        outline = 'white'            if active else '#2a3a4a'
        fg      = 'white'            if active else '#445566'
        m       = 2                                     # 여백
        cv = tk.Canvas(parent, width=size, height=size,
                       bg=bg, highlightthickness=0)
        cv.pack(side=tk.LEFT, padx=padx)
        cv.create_oval(m, m, size - m, size - m,
                       fill=c, outline=outline, width=1)
        cv.create_text(size // 2, size // 2, text=str(number),
                       fill=fg, font=('Malgun Gothic', font_size, 'bold'))
        return cv

    # ── [캔버스] 구성 ─────────────────────────────────────────────────────────
    def _build_canvas(self):
        self.canvas = tk.Canvas(
            self.root,
            width=CANVAS_W, height=CANVAS_H,
            bg='#050d1a',
            highlightthickness=3, highlightbackground='#FFD700',
        )
        self.canvas.pack(side=tk.LEFT, padx=14, pady=15)

        # ── v1.9.1: 4개 구멍 oval/라벨을 모두 미리 생성 ──────────────────────
        # state='normal'/'hidden'으로 1↔4 모드 전환 — destroy/create 비용 없음
        # 라벨 위치: 좌상/우상은 구멍 아래, 좌하/우하는 구멍 위 (캔버스 밖 안 나가게)
        self.hole_ovals: List[int]  = []
        self.hole_labels: List[int] = []
        for i, (hx, hy) in enumerate(LottoEngine.HOLE_CENTERS_4):
            # v1.9.4: 사용자 피드백 반영
            #   fill    #1a0a35(어두운보라) → #F0F8FF(거의흰색) → #85819A(중간값)
            #           = (133,129,154) RGB 정확한 중간 — 살짝 보라빛 회색
            #   outline #FFAAAA(분홍빨강) → #FF4444(빨강) — v1.9.2 복원
            oval = self.canvas.create_oval(
                hx - HOLE_R, hy - HOLE_R, hx + HOLE_R, hy + HOLE_R,
                fill='#85819A', outline='#FF4444', width=4, dash=(7, 4),
                state='hidden',     # 기본 hidden, _apply_hole_count로 활성화
            )
            # 라벨은 위쪽(상단) 구멍이면 아래에, 아래쪽 구멍이면 위에 배치
            label_y = hy + HOLE_R + 18 if hy < CANVAS_H / 2 else hy - HOLE_R - 18
            label = self.canvas.create_text(
                hx, label_y, text="당첨 구멍",
                fill='#FF4444', font=('Malgun Gothic', 13, 'bold'),
                state='hidden',
            )
            self.hole_ovals.append(oval)
            self.hole_labels.append(label)

        # 호환성: 기존 코드에서 self.hole_oval/hole_label을 참조하면 우상 구멍 가리킴
        self.hole_oval  = self.hole_ovals[1]    # 우상 (기존 위치)
        self.hole_label = self.hole_labels[1]

        # 캔버스 중앙 회차 제목 (item ID 저장 → 나중에 update_round() 로 갱신)
        self._canvas_title_id = self.canvas.create_text(
            CANVAS_W // 2, 30,
            text="제  ?회  로또  예상번호  추첨기",
            fill='#FFD700', font=('Malgun Gothic', 26, 'bold'),
        )

        # 활성 구멍 인덱스 — apply_hole_count_visual에서 갱신
        self._active_hole_indices: List[int] = [1]   # 기본 1구멍(우상)

    # ── v1.9.1: 구멍 개수 변경 시 가시성 갱신 (v1.9.2: 2구멍 추가) ────────────
    def apply_hole_count_visual(self, hole_count: int):
        """엔진의 hole_count와 동기화 — 활성 구멍만 보이도록 state 토글.

        인덱스 매핑 (HOLE_CENTERS_4 기준: 0=좌상, 1=우상, 2=좌하, 3=우하)
          1구멍 → [1]           : 우상만
          2구멍 → [1, 2]        : 우상 + 좌하 (대각선 대칭, v1.9.2)
          4구멍 → [0, 1, 2, 3]  : 모두
        """
        if hole_count == 4:
            self._active_hole_indices = [0, 1, 2, 3]
        elif hole_count == 2:
            self._active_hole_indices = [1, 2]   # 우상 + 좌하
        else:                                     # 1 또는 잘못된 값
            self._active_hole_indices = [1]      # 우상만 (기존 위치)

        for i, oval in enumerate(self.hole_ovals):
            new_state = 'normal' if i in self._active_hole_indices else 'hidden'
            self.canvas.itemconfig(oval, state=new_state)
            self.canvas.itemconfig(self.hole_labels[i], state=new_state)

