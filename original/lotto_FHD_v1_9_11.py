# 한자어 수사 변환  _num_to_korean         (v1.8.2 신규)
#
#  edge-tts가 "1번"을 받으면 "한 번"(고유어 수사+의존명사)으로 발음하는 문제 해결.
#  텍스트를 한자어로 풀어서 합성하면 "일번", "이번", "삼번" 식으로 정확히 발음.
#
#    1=일,  2=이,  3=삼,  4=사,  5=오,  6=육,  7=칠,  8=팔,  9=구
#    10=십, 15=십오, 20=이십, 32=삼십이, 45=사십오
# ══════════════════════════════════════════════════════════════════════════════
_KO_ONES = ('', '일', '이', '삼', '사', '오', '육', '칠', '팔', '구')
_KO_TENS = ('', '십', '이십', '삼십', '사십', '오십', '육십', '칠십', '팔십', '구십')


def _num_to_korean(n: int) -> str:
    """1~99 → 한자어 한국어 표기 ('육', '십오', '삼십이' 등).
    범위 밖이면 빈 문자열 반환."""
    if not (1 <= n <= 99):
        return ''
    if n < 10:
        return _KO_ONES[n]
    if n == 10:
        return '십'
    return _KO_TENS[n // 10] + _KO_ONES[n % 10]


