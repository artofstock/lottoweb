# 2.  _SpatialGrid  –  균일 그리드 공간 분할 (충돌 체크 O(n²) → O(n))
#
#  원리
#  ┌──────────────────────────────────────────────────────────────────────────┐
#  │  캔버스를 128×128 px 셀로 분할 (12열 × 9행 = 108셀)                    │
#  │  공 지름 = 64 px  →  두 공이 충돌하려면 중심 거리 < 64 px             │
#  │  거리 64 px < 셀 크기 128 px  →  같은 셀 + 인접 1셀 안에만 후보 존재  │
#  │                                                                          │
#  │  전방향(오른쪽·아래) 4셀만 순회 → 모든 페어를 중복 없이 한 번 생성    │
#  │                                                                          │
#  │  45개 공 기준:                                                           │
#  │    브루트포스: 45×44/2 = 990 쌍  (매 프레임 고정)                       │
#  │    그리드:     평균 ~83 쌍  →  약 12× 감소                              │
#  └──────────────────────────────────────────────────────────────────────────┘
# ══════════════════════════════════════════════════════════════════════════════
class _SpatialGrid:
    """
    균일 그리드로 근접 공 쌍만 추출.

    - build()  : O(n)   – 매 프레임 그리드 재구성
    - pairs()  : O(n+k) – 충돌 후보 쌍 반환  (k = 실제 후보 수, 평균 83)
    """

    # 검사 방향: 현재 셀에서 오른쪽·아래 4방향만 → 쌍 중복 없음
    #  (cx-1,cy+1) (cx,cy+1) (cx+1,cy+1)
    #  (cx-1,cy  ) [현재셀]  (cx+1,cy  )  ← (cx+1,cy) 만 사용
    #                        (cx+1,cy-1)
    _NEIGHBOR_DIRS: Tuple[Tuple[int, int], ...] = (
        (1, -1), (1, 0), (1, 1), (0, 1)
    )

    def __init__(self, cell_size: int = CELL_SIZE):
        self._cell = cell_size
        self._grid: Dict[Tuple[int, int], List['Ball']] = {}

    # ── 그리드 구축 ───────────────────────────────────────────────────────────
    def build(self, balls: List['Ball']):
        """공 목록으로 그리드를 재구성한다.  O(n)"""
        self._grid.clear()
        c = self._cell
        for b in balls:
            key = (int(b.x / c), int(b.y / c))
            if key in self._grid:
                self._grid[key].append(b)
            else:
                self._grid[key] = [b]

    # ── 후보 쌍 생성 ──────────────────────────────────────────────────────────
    def pairs(self) -> List[Tuple['Ball', 'Ball']]:
        """충돌 가능성이 있는 (b1, b2) 쌍을 중복 없이 반환한다."""
        result: List[Tuple['Ball', 'Ball']] = []
        grid   = self._grid

        for (cx, cy), cell_balls in grid.items():
            # ① 같은 셀 내 쌍
            n = len(cell_balls)
            for i in range(n):
                for j in range(i + 1, n):
                    result.append((cell_balls[i], cell_balls[j]))

            # ② 오른쪽·아래 방향 인접 셀과의 쌍
            for dcx, dcy in self._NEIGHBOR_DIRS:
                nb_balls = grid.get((cx + dcx, cy + dcy))
                if nb_balls:
                    for b1 in cell_balls:
                        for b2 in nb_balls:
                            result.append((b1, b2))

        return result

    # ── 디버그용 통계 ─────────────────────────────────────────────────────────
    def stats(self) -> Dict[str, int]:
        occupied = len(self._grid)
        total    = sum(len(v) for v in self._grid.values())
        return {'occupied_cells': occupied, 'balls': total}


# ══════════════════════════════════════════════════════════════════════════════
# 3.  LottoEngine  –  공 물리 + 통계 처리 (tkinter 없음)
# ══════════════════════════════════════════════════════════════════════════════
class LottoEngine:
    """번호 생성, 공 물리 계산, 통계 처리.
    UI에 전혀 의존하지 않으므로 단독 테스트 가능."""

    # ── 구멍 좌표 (v1.9.1: 단일 → 4구멍 모두 정의) ────────────────────────────
    # 인덱스 의미: 0=좌상, 1=우상, 2=좌하, 3=우하
    # 1구멍 모드는 인덱스 1(우상, 기존 위치)만 활성, 4구멍 모드는 전체 활성.
    HOLE_CENTERS_4: Tuple[Tuple[int, int], ...] = (
        (HOLE_R + 18,            HOLE_R + 18),             # 0: 좌상
        (CANVAS_W - HOLE_R - 18, HOLE_R + 18),             # 1: 우상  ← 기존
        (HOLE_R + 18,            CANVAS_H - HOLE_R - 18),  # 2: 좌하
        (CANVAS_W - HOLE_R - 18, CANVAS_H - HOLE_R - 18),  # 3: 우하
    )

    # 호환성: 기존 코드/외부 참조용 단일 구멍 좌표 (= 우상)
    # v1.9.1 이전엔 클래스 변수였으므로 유지 — 새 코드는 self._active_holes 사용
    HOLE_CENTER: Tuple[int, int] = HOLE_CENTERS_4[1]

    def __init__(self, max_games: int = 100, hole_count: int = 1):
        self.max_games = max_games
        self.balls:          List[Ball] = []
        self.drawn_numbers:  List[int]  = []
        self.freq:           Dict[int, int] = {n: 0 for n in range(1, 46)}
        self.total_games:    int = 0
        # 충돌 감지용 공간 분할 그리드
        self._grid = _SpatialGrid()
        # 목표속도 (accelerate_balls 호출마다 단계적으로 상승)
        self.target_speed: float = TARGET_SPEED_INIT
        # v1.9.1: 활성 구멍 개수 (1 또는 4)
        self.set_hole_count(hole_count)

    # ── v1.9.1: 활성 구멍 개수 변경 (v1.9.2: 2구멍 모드 추가) ──────────────────
    def set_hole_count(self, count: int):
        """활성 구멍 개수를 1, 2, 또는 4로 설정한다.

        1 → 우상 한 곳만 (기존 동작 유지, HOLE_CENTERS_4[1])
        2 → 우상 + 좌하 (대각선 대칭, HOLE_CENTERS_4[1] + [2])
        4 → 4모서리 모두

        v1.9.2: 2구멍은 화면 중심 기준 180° 회전 대칭 위치 — 시각적 균형.
                자석은 가까운 1개에만 작용하므로 두 구멍이 합력 균형을 이루지 않음.
        """
        if count not in (1, 2, 4):
            log.warning(f"잘못된 hole_count={count} → 1로 강제")
            count = 1
        self.hole_count = count
        if count == 1:
            self._active_holes: Tuple[Tuple[int, int], ...] = (
                self.HOLE_CENTERS_4[1],   # 우상
            )
        elif count == 2:
            # 우상(1) + 좌하(2) — 대각선 대칭
            self._active_holes = (
                self.HOLE_CENTERS_4[1],   # 우상
                self.HOLE_CENTERS_4[2],   # 좌하
            )
        else:  # count == 4
            self._active_holes = self.HOLE_CENTERS_4

    @property
    def active_holes(self) -> Tuple[Tuple[int, int], ...]:
        """현재 활성화된 구멍 좌표 튜플 (UI 등 외부 참조용)."""
        return self._active_holes

    # ── 공 초기화 ─────────────────────────────────────────────────────────────
    def create_all_balls(self) -> List[Ball]:
        """1~45번 공을 새로 만들어 반환한다.

        생성 순서를 매 게임마다 셔플한다.
        random.randint 내부 상태가 순서와 상관없어져
        번호와 초기 위치·속도의 구조적 상관관계가 제거된다.
        """
        self.balls.clear()
        numbers = list(range(1, 46))
        random.shuffle(numbers)          # 번호-위치 상관관계 제거
        for n in numbers:
            self.balls.append(self._make_ball(n))
        return list(self.balls)

    def _make_ball(self, number: int) -> Ball:
        r  = BALL_R
        # v1.9.6 공정성 수정 ────────────────────────────────────────────────────
        # 기존: y = randint(r+60, CANVAS_H-r-5) → 위쪽 60px / 아래쪽 5px 비대칭
        #   · 위쪽 구멍(y=54)과 최단 거리: 38px
        #   · 아래쪽 구멍(y=996)과 최단 거리: 17px (← 편향)
        #   → 4·2구멍 모드에서 아래쪽 구멍이 통계적으로 살짝 유리했음
        # 신규: 위·아래 모두 60px 버퍼 — 모든 활성 구멍과 최단 거리 38px 동일
        #   · 1구멍 모드(우상)도 동일 — 더 좁아지지만 일관성 우선
        #   · 위쪽 60px 은 캔버스 제목(y=30, 폰트 26pt) 가림 방지 목적이므로 유지
        x  = random.randint(r + 5,  CANVAS_W - r - 5)
        y  = random.randint(r + 60, CANVAS_H - r - 60)
        vx = random.uniform(-13, 13)   # 이전 ±9 → ±13 (활발한 초기 흐름)
        vy = random.uniform(-13, 13)
        if abs(vx) < 4: vx = 4 * (1 if vx >= 0 else -1)   # 이전 최소 2 → 4
        if abs(vy) < 4: vy = 4 * (1 if vy >= 0 else -1)
        # v1.9.0: prev_x/prev_y는 첫 프레임에 현재 위치로 초기화
        # (이동량 0 → Swept Sphere 검사 자동 스킵, 안전)
        return Ball(number=number, x=x, y=y, vx=vx, vy=vy, r=r,
                    color=ball_color(number), prev_x=x, prev_y=y)

    # ── 물리: 자석 (모든 공 동등하게 끌어당김) ──────────────────────────────
    def apply_magnet(self):
        """
        구멍 방향으로 모든 공에 동일한 인력을 가한다.
        어떤 공이 먼저 들어갈지는 전적으로 물리(위치·속도·충돌)가 결정한다.
        호출 여부는 LottoMachine의 상태 머신이 판단한다.

        v1.9.1: 4구멍 모드 지원
        ─────────────────────────────────────────────────────────────
        각 공마다 가장 가까운 구멍 1개에만 인력 적용.
        4개 모두에 동시 적용하면 4방향 합력이 균형을 이뤄 공이
        중심부에 정지할 위험이 있음 (특히 캔버스 정중앙).
        가까운 1개만 → 자연스럽게 그 방향으로 빨려들어감.
        """
        for b in self.balls:
            # 가장 가까운 구멍 찾기 (1구멍 모드면 어차피 하나뿐 → 비용 거의 0)
            min_dist_sq = float('inf')
            nearest = None
            for hx, hy in self._active_holes:
                dx_h = hx - b.x
                dy_h = hy - b.y
                d_sq = dx_h * dx_h + dy_h * dy_h
                if d_sq < min_dist_sq:
                    min_dist_sq = d_sq
                    nearest = (hx, hy, dx_h, dy_h)

            if nearest is None:
                continue
            hx, hy, dx, dy = nearest
            dist = math.sqrt(min_dist_sq)
            if 0 < dist < MAGNET_RANGE:
                force = MAGNET_STRENGTH * (1 - dist / MAGNET_RANGE)
                b.vx += (dx / dist) * force
                b.vy += (dy / dist) * force

    # ── 물리: 이동 + 벽 반사 + 목표속도 추적 ────────────────────────────────
    def move_balls(self):
        """
        매 프레임 공 위치를 갱신한다.

        속도 관리 전략 (DAMPING 방식 → 목표속도 추적 방식으로 변경)
        ─────────────────────────────────────────────────────────────
        · 공 속도 < target_speed  →  SPEED_PUSH 만큼 방향 유지하며 가속
          (느려질수록 더 세게 밀어줌 → 시간이 갈수록 빨라지는 구조)
        · 공 속도 > MAX_SPEED     →  클램프
        · target_speed 자체는 accelerate_balls() 가 8초마다 단계적으로 올림
        """
        tgt = self.target_speed
        for b in self.balls:
            # v1.9.0: Swept Sphere 검사용 이전 위치 저장
            # check_hole()에서 이번 프레임 이동 경로 전체를 검사하기 위함
            b.prev_x = b.x
            b.prev_y = b.y

            spd = math.hypot(b.vx, b.vy)

            if spd > MAX_SPEED:                      # 상한 클램프
                ratio = MAX_SPEED / spd
                b.vx *= ratio;  b.vy *= ratio
            elif spd < tgt and spd > 1e-6:           # 목표속도 미만 → 가속
                # 방향은 유지, 크기만 SPEED_PUSH 만큼 키움
                ratio = (spd + SPEED_PUSH) / spd
                b.vx *= ratio;  b.vy *= ratio
            elif spd < 1e-6:                         # 완전 정지 극단 케이스
                angle = random.uniform(0, math.tau)
                b.vx  = math.cos(angle) * tgt
                b.vy  = math.sin(angle) * tgt

            # 위치 갱신
            b.x += b.vx
            b.y += b.vy

            # 벽 반사 (반발계수 적용)
            if b.x - b.r < 0:
                b.x  = b.r
                b.vx = abs(b.vx) * RESTITUTION_WALL
            elif b.x + b.r > CANVAS_W:
                b.x  = CANVAS_W - b.r
                b.vx = -abs(b.vx) * RESTITUTION_WALL

            if b.y - b.r < 0:
                b.y  = b.r
                b.vy = abs(b.vy) * RESTITUTION_WALL
            elif b.y + b.r > CANVAS_H:
                b.y  = CANVAS_H - b.r
                b.vy = -abs(b.vy) * RESTITUTION_WALL

    # ── 물리: 충돌 (공간 분할 그리드 + 정확한 임펄스 모델) ──────────────────
    def check_collisions(self):
        """
        _SpatialGrid로 후보 쌍을 좁힌 뒤 물리적으로 정확한 충돌 반응을 적용한다.

        개선 내역
        ─────────
        ① 반발계수(RESTITUTION_BALL=0.85)  충돌마다 에너지 ~15% 손실
            impulse J = -(1 + e) * vn / (1/m1 + 1/m2)
            기존:   vn 전부 교환 (e=1, 에너지 무손실)

        ② 접선 마찰(FRICTION_TANGENT=0.025)  비스듬한 충돌 후 방향 자연스럽게 틀어짐
            쿨롱 마찰 간략화: |J_t| ≤ FRICTION_TANGENT × |J_n|
            기존:   접선 방향 완전 미끄럼 (마찰 없음)

        ③ 위치 보정  각 공의 질량 역비로 겹침 분리 (동질량이면 절반씩)
        """
        self._grid.build(self.balls)

        for b1, b2 in self._grid.pairs():
            dx   = b1.x - b2.x
            dy   = b1.y - b2.y
            dist = math.hypot(dx, dy)
            md   = b1.r + b2.r
            if dist >= md:
                continue

            # ── 충돌 법선·접선 벡터 ──────────────────────────────────────────
            if dist < 1e-9:          # 완전 중첩: 임의 방향으로 밀어냄
                angle = random.uniform(0, math.tau)
                nx, ny = math.cos(angle), math.sin(angle)
            else:
                nx = dx / dist;  ny = dy / dist

            tx = -ny;  ty = nx    # 접선: 법선에 수직

            # ── 상대속도 분해 ─────────────────────────────────────────────────
            rvx = b1.vx - b2.vx
            rvy = b1.vy - b2.vy
            vn  = rvx * nx + rvy * ny   # 법선 방향 상대속도
            vt  = rvx * tx + rvy * ty   # 접선 방향 상대속도

            if vn > 0:               # 이미 멀어지는 중 → 건드리지 않음
                continue

            # ── ① 법선 임펄스 (반발계수 적용) ────────────────────────────────
            # J_n = -(1+e) * vn / (1/m1 + 1/m2)
            inv_mass_sum = 1.0 / b1.mass + 1.0 / b2.mass
            Jn = -(1.0 + RESTITUTION_BALL) * vn / inv_mass_sum

            # ── ② 접선 임펄스 (쿨롱 마찰: |Jt| ≤ μ|Jn|) ────────────────────
            # 마찰력이 미끄럼을 완전히 멈출 수 있는 최대 크기를 넘지 않게 제한
            Jt_max = FRICTION_TANGENT * abs(Jn)
            Jt_raw = -vt / inv_mass_sum   # 미끄럼을 완전히 멈추는 임펄스 크기
            Jt     = max(-Jt_max, min(Jt_max, Jt_raw))

            # ── 속도 갱신 ────────────────────────────────────────────────────
            b1.vx += (Jn * nx + Jt * tx) / b1.mass
            b1.vy += (Jn * ny + Jt * ty) / b1.mass
            b2.vx -= (Jn * nx + Jt * tx) / b2.mass
            b2.vy -= (Jn * ny + Jt * ty) / b2.mass

            # ── ③ 위치 겹침 보정 (질량 역비율로 분리) ───────────────────────
            ov       = (md - dist) + 0.5    # 0.5px 여유를 더해 다음 프레임 재충돌 방지
            w1       = (1.0 / b1.mass) / inv_mass_sum   # 동질량 → 0.5
            w2       = 1.0 - w1
            b1.x    += nx * ov * w1;   b1.y += ny * ov * w1
            b2.x    -= nx * ov * w2;   b2.y -= ny * ov * w2

    # ── 물리: 구멍 감지 (먼저 들어온 공이 당첨, Swept Sphere로 터널링 방지) ─
    def check_hole(self) -> Optional[Ball]:
        """
        구멍 안에 완전히 들어온 공을 포획한다.
        어떤 공이든 먼저 들어오면 당첨 — 사전 결정 없음.

        v1.9.0: Swept Sphere (선분-원 거리) 검사 추가
        ───────────────────────────────────────────────────────
        문제: HOLE_R(36) - BALL_R(32) = 4px 캡처영역 vs MAX_SPEED 26 px/frame
              → 빠른 공이 한 프레임에 캡처영역 통째로 건너뛸 수 있음 (터널링)
              → 빠른 공일수록 잡힐 확률이 낮아지는 미세한 속도 편향 발생

        해결: 이전 위치(prev_x, prev_y)와 현재 위치(x, y)를 잇는 선분이
              캡처원에 한 번이라도 진입했는지 검사 — 빠른 공도 경로상에서 잡힘.

        v1.9.1: 활성 구멍 모두 검사 (1개 또는 4개)
              · 한 프레임에 한 공만 캡처 (먼저 발견된 공 반환)
              · 동시 캡처는 다음 프레임에서 자연스럽게 처리 → 슬롯/비프 차례대로
        """
        capture_dist_sq = (HOLE_R - BALL_R) ** 2   # 4px → 16

        for ball in self.balls[:]:
            # 활성 구멍 각각에 대해 ① 빠른 경로 → ② Swept Sphere 순서로 검사
            for hx, hy in self._active_holes:
                # ── ① 빠른 경로: 현재 위치 검사 ─────────────────────────────
                ddx = ball.x - hx
                ddy = ball.y - hy
                if ddx * ddx + ddy * ddy <= capture_dist_sq:
                    self.balls.remove(ball)
                    self.drawn_numbers.append(ball.number)
                    return ball

                # ── ② 느린 경로: Swept Sphere (선분-점 최단거리) ────────────
                seg_dx = ball.x - ball.prev_x
                seg_dy = ball.y - ball.prev_y
                seg_len_sq = seg_dx * seg_dx + seg_dy * seg_dy
                if seg_len_sq < 64.0:                  # 8px 이하 이동 → 스킵
                    continue

                to_h_x = hx - ball.prev_x
                to_h_y = hy - ball.prev_y
                t = (to_h_x * seg_dx + to_h_y * seg_dy) / seg_len_sq
                if t <= 0.0 or t >= 1.0:               # 선분 양 끝 밖
                    continue

                closest_x = ball.prev_x + t * seg_dx
                closest_y = ball.prev_y + t * seg_dy
                cdx = closest_x - hx
                cdy = closest_y - hy
                if cdx * cdx + cdy * cdy <= capture_dist_sq:
                    # 경로상에서 캡처 — 공 위치를 캡처 지점으로 보정
                    ball.x = closest_x
                    ball.y = closest_y
                    self.balls.remove(ball)
                    self.drawn_numbers.append(ball.number)
                    log.debug(f"공 {ball.number} 터널링 캡처 — t={t:.2f} "
                              f"hole=({hx},{hy}) 이동량 {math.sqrt(seg_len_sq):.1f}px")
                    return ball

        return None

    # ── 물리: 단계적 목표속도 상승 (8초마다 호출) ────────────────────────────
    def accelerate_balls(self):
        """
        target_speed를 ACCEL_RATE 배씩 올린다.
        move_balls() 가 매 프레임 target_speed 를 향해 공을 밀어주므로
        호출될수록 전체 공이 확실히 빨라지는 구조가 된다.
        """
        self.target_speed = min(
            self.target_speed * ACCEL_RATE,
            TARGET_SPEED_MAX,
        )

    # ── 통계 ──────────────────────────────────────────────────────────────────
    def record_draw(self, numbers: List[int]):
        """한 게임 결과를 통계에 반영한다."""
        self.total_games += 1
        for n in numbers:
            self.freq[n] += 1

    def reset_stats(self):
        """파일 교체 시 통계를 초기화한다."""
        self.freq        = {n: 0 for n in range(1, 46)}
        self.total_games = 0

    def sorted_freq(self) -> List[Tuple[int, int]]:
        """빈도 내림차순, 번호 오름차순으로 정렬된 (번호, 횟수) 리스트."""
        return sorted(self.freq.items(), key=lambda x: (-x[1], x[0]))

    def nearest_ball_distance(self) -> float:
        """모든 활성 구멍 × 모든 공 중 최단 거리.
        (UI 발광 효과의 강도를 결정)
        v1.9.1: 4구멍 모드에서도 가장 가까운 페어 거리 사용."""
        if not self.balls:
            return float('inf')
        min_d = float('inf')
        for hx, hy in self._active_holes:
            for b in self.balls:
                d = math.hypot(b.x - hx, b.y - hy)
                if d < min_d:
                    min_d = d
        return min_d

    def nearest_distance_per_hole(self) -> List[float]:
        """v1.9.1: 활성 구멍별 가장 가까운 공까지의 거리 리스트.
        UI에서 각 구멍 발광 강도를 따로 계산할 때 사용."""
        if not self.balls:
            return [float('inf')] * len(self._active_holes)
        result = []
        for hx, hy in self._active_holes:
            d = min(math.hypot(b.x - hx, b.y - hy) for b in self.balls)
            result.append(d)
        return result

    # ── 상태 초기화 ───────────────────────────────────────────────────────────
    def reset_draw(self):
        """한 게임 시작 시 공·추첨번호만 초기화 (통계는 유지)."""
        self.balls.clear()
        self.drawn_numbers.clear()
        self.target_speed = TARGET_SPEED_INIT


