    def add_ball(self, ball: Ball):
        """엔진이 생성한 Ball을 캔버스에 그린다."""
        r   = ball.r
        oid = self.canvas.create_oval(
            ball.x - r, ball.y - r, ball.x + r, ball.y + r,
            fill=ball.color, outline='white', width=3,
        )
        tid = self.canvas.create_text(
            ball.x, ball.y, text=str(ball.number),
            fill='white', font=('Malgun Gothic', 18, 'bold'),
        )
        self._ball_ids[ball.number] = (oid, tid)

    def remove_ball(self, ball: Ball):
        """포획된 공의 캔버스 아이템을 삭제한다."""
        ids = self._ball_ids.pop(ball.number, None)
        if ids:
            self.canvas.delete(ids[0])
            self.canvas.delete(ids[1])

    def update_ball_positions(self, balls: List[Ball]):
        """매 프레임 모든 공 위치를 캔버스에 반영한다."""
        for b in balls:
            ids = self._ball_ids.get(b.number)
            if ids:
                oid, tid = ids
                self.canvas.coords(oid, b.x - b.r, b.y - b.r,
                                        b.x + b.r, b.y + b.r)
                self.canvas.coords(tid, b.x, b.y)

    def clear_all_balls(self):
        """캔버스에 있는 모든 공 아이템을 삭제한다."""
        for oid, tid in self._ball_ids.values():
            self.canvas.delete(oid)
            self.canvas.delete(tid)
        self._ball_ids.clear()

