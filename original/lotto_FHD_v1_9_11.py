# 게임 상태 머신  GameState · _StateMachine
#
#  기존 문제
#  ┌─────────────────────────────────────────────────────────────────────────┐
#  │  animation_running · hole_active · _draw_locked · _max_games_reached   │
#  │  → 4개 bool의 조합이 16가지인데 실제 유효 조합은 5가지뿐               │
#  │  → IDLE / OVERLAY / COUNTDOWN 이 모두 (False,False,False)로 동일       │
#  │    → OVERLAY 중 start_draw() 가 통과될 수 있는 버그                    │
#  └─────────────────────────────────────────────────────────────────────────┘
#
#  개선: 상태를 하나의 Enum으로 통합
#  ┌─────────────────────────────────────────────────────────────────────────┐
#  │  IDLE  ──(start)──▶  RUNNING  ──(done)──▶  OVERLAY                    │
#  │   ▲                                         │       │                  │
#  │   │                           (auto=True)   │  (auto=False/max)        │
#  │   │                                         ▼       ▼                  │
#  │   └──────────────────────────────────── COUNTDOWN  IDLE                │
#  │                                             │                          │
#  │   reset() 는 어느 상태에서든 → IDLE          │                          │
#  │                               (tick=0) ─────┘                          │
#  └─────────────────────────────────────────────────────────────────────────┘
# ══════════════════════════════════════════════════════════════════════════════

class GameState(Enum):
    IDLE      = auto()   # 대기: 시작 전 / 리셋 후
    RUNNING   = auto()   # 추첨 진행: 공이 구멍을 향해 튀어다니는 중
    OVERLAY   = auto()   # 번호 발표: 오버레이 애니메이션 재생 중
    COUNTDOWN = auto()   # 자동 진행: 다음 게임까지 카운트다운 중
    COMPLETED = auto()   # max_games 도달: 새 파일 생성 후 사용자 입력 대기


class _StateMachine:
    """
    GameState 전이를 관리하는 상태 머신.

    · 허용된 전이(ALLOWED)만 통과 → 잘못된 전이는 ValueError
    · transition() 한 곳에서만 상태를 바꾸므로 불일치 상태 불가
    · current 프로퍼티로 어디서든 현재 상태 조회

    v1.7 변경
      · COMPLETED 상태 추가 → bool flag (_max_games_reached) 제거
      · 중복 전이 항목 정리 (set이라 동작은 동일하나 의도 명확화)
    """

    # 허용된 (from → to) 전이 집합
    _ALLOWED: Set[Tuple[GameState, GameState]] = {
        (GameState.IDLE,      GameState.RUNNING),
        (GameState.RUNNING,   GameState.OVERLAY),
        (GameState.RUNNING,   GameState.IDLE),       # 6개 미달 종료 (edge case)
        (GameState.OVERLAY,   GameState.IDLE),       # 자동진행 OFF
        (GameState.OVERLAY,   GameState.COUNTDOWN),  # 자동진행 ON
        (GameState.OVERLAY,   GameState.COMPLETED),  # max_games 도달
        (GameState.COUNTDOWN, GameState.RUNNING),    # 카운트다운 종료
        (GameState.COUNTDOWN, GameState.IDLE),       # 카운트다운 중 리셋
        (GameState.COMPLETED, GameState.IDLE),       # 사용자 다시 시작/리셋
        # v1.9.6: can_start() 가 COMPLETED 도 허용하므로 직접 전이도 정식 허용
        # (기존엔 _after_overlay_done 에서 force=True 로 즉시 IDLE 보내서 가려져 있던
        #  잠재 크래시 경로 — 코드 순서가 바뀌면 ValueError 폭발. 명시적 허용으로 안전)
        (GameState.COMPLETED, GameState.RUNNING),
    }

    def __init__(self):
        self._state = GameState.IDLE

    @property
    def current(self) -> GameState:
        return self._state

    def transition(self, to: GameState, force: bool = False) -> GameState:
        """
        상태를 전이한다.

        force=True : reset() 등 어디서든 IDLE로 강제 전이
        force=False: _ALLOWED에 없는 전이는 ValueError 발생
        """
        pair = (self._state, to)
        if not force and pair not in self._ALLOWED:
            raise ValueError(
                f"[StateMachine] 허용되지 않은 전이: "
                f"{self._state.name} → {to.name}"
            )
        prev        = self._state
        self._state = to
        return prev   # 이전 상태를 반환 (필요 시 활용)

    # ── 상태 확인 헬퍼 ────────────────────────────────────────────────────────
    def is_idle(self)      -> bool: return self._state == GameState.IDLE
    def is_running(self)   -> bool: return self._state == GameState.RUNNING
    def is_overlay(self)   -> bool: return self._state == GameState.OVERLAY
    def is_countdown(self) -> bool: return self._state == GameState.COUNTDOWN
    def is_completed(self) -> bool: return self._state == GameState.COMPLETED
    def can_start(self)    -> bool:
        # IDLE 또는 COMPLETED(완료 후)에서 시작 가능
        return self._state in (GameState.IDLE, GameState.COMPLETED)


