    # ── 동기 합성 (블로킹 — 워커 또는 prebuild 스레드에서만 호출) ─────────────
    def _synthesize_sync(self, text: str, path: str,
                         max_retries: int = 2,
                         verbose: bool = True) -> bool:
        """edge-tts로 한 텍스트를 동기 합성한다. 성공 시 True.

        v1.8.1: 일시적 네트워크 실패에 대비해 max_retries 만큼 재시도.
                verbose=False면 실패 로그를 DEBUG로 (캐시 빌드 중 노이즈 방지)
        """
        if os.path.exists(path):
            return True

        last_err = None
        for attempt in range(max_retries + 1):
            try:
                # v1.9.6: 모듈 레벨 asyncio import 사용 (재import 제거)
                async def _save():
                    # v1.8.2: rate 파라미터로 발음 속도 조정
                    comm = self._edge_tts.Communicate(
                        text, self.VOICE, rate=self.RATE)
                    await comm.save(path)

                asyncio.run(_save())
                # 빈 파일이면 실패로 간주 (네트워크 실패 시 0바이트 가능)
                if os.path.getsize(path) < 100:
                    os.remove(path)
                    raise RuntimeError("합성된 파일이 너무 작음")
                return True
            except Exception as e:
                last_err = e
                # 잔재 파일 정리
                try:
                    if os.path.exists(path):
                        os.remove(path)
                except Exception:
                    pass
                # 재시도 대기 (지수 백오프 — 1초, 2초)
                if attempt < max_retries:
                    time.sleep(1.0 * (attempt + 1))

        # 최종 실패 — 로그는 verbose에 따라 등급 조정
        if verbose:
            log.warning(f"TTS 합성 실패 [{text[:20]}]: {last_err}")
        else:
            log.debug(f"TTS 합성 실패 [{text[:20]}]: {last_err}")
        return False

    # ── 사전 캐싱 (백그라운드) ────────────────────────────────────────────────
    def _prebuild_cache(self):
        """1~45 숫자 + 고정 문구를 백그라운드에서 미리 합성한다.

        v1.8.1: 캐시 빌드 중 개별 실패 로그는 DEBUG로 — 콘솔 노이즈 방지.
                 결과는 마지막에 한 줄로 요약 (성공/총수/소요시간)
        v1.9.0: asyncio.gather + Semaphore 로 동시 6개 합성 (병렬화).
                 첫 실행 캐싱 시간 ~20초 → ~5초 단축.
                 단, 이미 모두 캐시된 상태면 합성 스킵 (기존 파일 그대로 사용)
        """
        log.info("TTS 캐시 빌드 시작 (백그라운드, 동시 6개)")
        t0 = time.perf_counter()

        # ── 합성할 (text, path) 쌍을 모은다 (이미 있는 건 제외) ────────────
        tasks: List[Tuple[str, str]] = []
        for key, text in self.FIXED_TEXTS.items():
            p = self._fixed_path(key)
            if not os.path.exists(p):
                tasks.append((text, p))
        for n in range(1, 46):
            p = self._num_path(n)
            if not os.path.exists(p):
                tasks.append((self._num_text(n), p))

        total = 45 + len(self.FIXED_TEXTS)
        already = total - len(tasks)

        if not tasks:
            self._cache_ready = True
            log.info(f"TTS 캐시 모두 존재 — {total}/{total} (합성 스킵)")
            return

        # ── 병렬 합성 (단일 이벤트 루프에서 gather) ────────────────────────
        ok_async = self._gather_synthesize(tasks)

        ok_total = already + ok_async
        elapsed = time.perf_counter() - t0
        self._cache_ready = (ok_total == total)

        if ok_total == total:
            log.info(f"TTS 캐시 빌드 완료 — {ok_total}/{total} 성공 "
                     f"({elapsed:.1f}초, 신규 합성 {ok_async}개)")
        elif ok_total == already:
            log.warning(
                f"TTS 캐시 빌드 신규분 전부 실패 — {ok_total}/{total} "
                f"({elapsed:.1f}초)\n"
                f"  → 네트워크/DNS 문제 가능성. 단축키 T 로 재시도 가능"
            )
        else:
            log.warning(
                f"TTS 캐시 빌드 부분 실패 — {ok_total}/{total} "
                f"({elapsed:.1f}초)  단축키 T 로 누락분만 재시도 가능"
            )

    def _gather_synthesize(self, tasks: List[Tuple[str, str]],
                            concurrency: int = 6) -> int:
        """v1.9.0: 단일 이벤트 루프에서 여러 합성 작업을 병렬 실행.

        Semaphore로 동시 실행을 concurrency개로 제한 (서버 부담·DNS 폭주 방지).
        반환: 성공 개수

        v1.9.6: 모듈 레벨 asyncio import 사용 (try/except 폴백 단순화)
        """
        sem = None  # 루프 안에서 만들어야 함
        ok = 0
        ok_lock = threading.Lock()

        async def _one(text: str, path: str):
            nonlocal ok
            if self._stop:
                return
            if os.path.exists(path):
                with ok_lock:
                    ok += 1
                return
            async with sem:
                # edge-tts 내부적으로 asyncio 사용 → 루프 안에서 직접 호출 가능
                for attempt in range(3):    # 0, 1, 2 = 총 3회
                    if self._stop:
                        return
                    try:
                        comm = self._edge_tts.Communicate(
                            text, self.VOICE, rate=self.RATE)
                        await comm.save(path)
                        # 빈 파일 검증
                        if os.path.getsize(path) < 100:
                            os.remove(path)
                            raise RuntimeError("합성 파일이 너무 작음")
                        with ok_lock:
                            ok += 1
                        return
                    except Exception as e:
                        try:
                            if os.path.exists(path):
                                os.remove(path)
                        except Exception:
                            pass
                        if attempt < 2:
                            await asyncio.sleep(1.0 * (attempt + 1))
                        else:
                            log.debug(f"TTS 합성 최종 실패 [{text[:20]}]: {e}")

        async def _main():
            nonlocal sem
            sem = asyncio.Semaphore(concurrency)
            await asyncio.gather(*(_one(t, p) for t, p in tasks))

        try:
            asyncio.run(_main())
        except Exception as e:
            log.warning(f"병렬 TTS 합성 루프 실패: {e}")

        return ok

    def retry_cache(self):
        """v1.8.1: 단축키 T로 호출 — 누락된 캐시만 다시 시도."""
        if self._backend == 'silent':
            log.info("TTS 백엔드 비활성 — 재시도 불가")
            return
        log.info("TTS 캐시 재시도 시작 (단축키 T)")
        threading.Thread(target=self._prebuild_cache, daemon=True).start()

    # ── 재생 (블로킹) ─────────────────────────────────────────────────────────
    def _play_file_blocking(self, path: str):
        """mp3 파일 한 개를 끝까지 재생한다.

        v1.9.6: 재생 중 _enabled 도 함께 체크 → 사용자가 발표 도중 🎙 OFF 하면
                현재 재생도 즉시 정지 (기존엔 현재 재생은 끝까지 진행됨).
        """
        if not os.path.exists(path):
            return
        try:
            mx = self._pygame.mixer
            mx.music.load(path)
            mx.music.play()
            while mx.music.get_busy():
                time.sleep(0.03)
                if self._stop or not self._enabled:
                    mx.music.stop()
                    return
        except Exception as e:
            log.warning(f"TTS 재생 실패 [{os.path.basename(path)}]: {e}")

    # ── 워커 스레드: 큐에서 항목 꺼내 순차 재생 ───────────────────────────────
    def _run(self):
        while not self._stop:
            try:
                item = self._queue.get(timeout=0.3)
            except _queue_mod.Empty:
                continue
            if item is None:                   # shutdown sentinel
                break
            try:
                kind, payload = item
                if not self._enabled:          # 큐 적재 후 사용자가 OFF한 경우
                    continue
                if kind == 'num':
                    n = payload
                    p = self._num_path(n)
                    if not os.path.exists(p):
                        # 캐시 미완 — 즉석 동기 합성 (v1.8.2: 한자어 발음)
                        self._synthesize_sync(self._num_text(n), p)
                    self._play_file_blocking(p)
                elif kind == 'fixed':
                    key = payload
                    p = self._fixed_path(key)
                    if not os.path.exists(p):
                        self._synthesize_sync(self.FIXED_TEXTS[key], p)
                    self._play_file_blocking(p)
                elif kind == 'numbers':
                    # 6개 번호 연속 발표 ("일번 오번 ... 사십오번")
                    for n in payload:
                        if self._stop or not self._enabled:
                            break
                        p = self._num_path(n)
                        if not os.path.exists(p):
                            self._synthesize_sync(self._num_text(n), p)
                        self._play_file_blocking(p)
                        time.sleep(0.12)       # 번호 사이 호흡
            except Exception as e:
                log.warning(f"TTS 워커 처리 실패: {e}")
            finally:
                # v1.8.4: 재생 종료 → pending 감소 (is_busy 판정용)
                with self._pending_lock:
                    self._pending = max(0, self._pending - 1)

    # ── 공개 API ──────────────────────────────────────────────────────────────
    def speak_number(self, n: int):
        """N번 음성 안내 (1~45)."""
        if not self._enabled or self._backend == 'silent':
            return
        if not (1 <= n <= 45):
            return
        # v1.8.4: 큐 적재와 동시에 pending 증가 (is_busy 정확성)
        with self._pending_lock:
            self._pending += 1
        self._queue.put(('num', n))

    def speak_fixed(self, key: str):
        """고정 문구 (FIXED_TEXTS의 키) 음성 안내."""
        if not self._enabled or self._backend == 'silent':
            return
        if key not in self.FIXED_TEXTS:
            return
        with self._pending_lock:
            self._pending += 1
        self._queue.put(('fixed', key))

    def speak_numbers(self, numbers: List[int]):
        """6개 번호 연속 발표."""
        if not self._enabled or self._backend == 'silent':
            return
        valid = [n for n in numbers if 1 <= n <= 45]
        if valid:
            with self._pending_lock:
                self._pending += 1
            self._queue.put(('numbers', valid))

    def is_busy(self) -> bool:
        """v1.8.4: 재생 대기/진행 중 항목이 있는가.

        LottoUI._reveal_chain 이 다음 번호 공개 타이밍을 결정할 때 사용.
        True → TTS 아직 재생 중, 기다려야 함
        False → 큐 비어있고 재생 완료, 다음 번호로 넘어갈 수 있음
        """
        with self._pending_lock:
            return self._pending > 0

    def set_enabled(self, value: bool):
        """TTS ON/OFF 토글. silent 백엔드면 항상 OFF."""
        self._enabled = bool(value) and (self._backend != 'silent')

    @property
    def enabled(self) -> bool:
        return self._enabled

    @property
    def available(self) -> bool:
        """TTS 백엔드가 사용 가능한가 (사용자 토글과 무관)."""
        return self._backend != 'silent'

    @property
    def backend(self) -> str:
        return self._backend

    def shutdown(self):
        """앱 종료 시 워커를 안전하게 멈춘다.

        v1.9.6: 현재 재생 중인 mp3가 있다면 즉시 stop() 호출 → 종료 응답성 ↑
                (asyncio.run 진행 중이면 어쩔 수 없이 끝까지 대기 — daemon 스레드라
                 메인 종료 시 강제 정리됨)
        """
        self._stop = True
        # 재생 중인 음악 즉시 정지 (있다면)
        try:
            if self._backend != 'silent' and hasattr(self, '_pygame'):
                mx = self._pygame.mixer
                if mx.get_init() and mx.music.get_busy():
                    mx.music.stop()
        except Exception:
            pass
        try:
            self._queue.put(None, timeout=0.1)
        except Exception:
            pass


