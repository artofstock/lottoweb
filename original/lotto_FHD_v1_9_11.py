# 사운드 엔진  _SoundEngine
#
#  설계 원칙
#  ┌─────────────────────────────────────────────────────────────────────────┐
#  │  ① 백엔드 자동 감지: pygame ▶ winsound ▶ 무음(silent)                  │
#  │     실행 환경에 맞는 백엔드를 자동으로 선택하므로                        │
#  │     Windows·Mac·Linux 어디서나 동작한다.                                │
#  │                                                                         │
#  │  ② 우선순위 큐 (PriorityQueue)                                          │
#  │     CRITICAL(0): 포획·시작·완료 팡파레 → 절대 스킵하지 않음             │
#  │     NORMAL  (1): 카운트다운 틱 등   → 큐 혼잡 시 스킵 허용             │
#  │     기존 문제: 틱 3개가 쌓이면 팡파레도 같이 버려졌음                   │
#  │                                                                         │
#  │  ③ pygame 백엔드: numpy 없이 bytearray로 사인파 합성                    │
#  │     · 크로스플랫폼                                                      │
#  │     · 페이드아웃 12ms → 클릭 잡음(pop) 제거                            │
#  │     · 합성 캐시: 같은 (freq, dur) 요청은 재합성 없이 재사용             │
#  │                                                                         │
#  │  ④ winsound 백엔드: Windows 전용 폴백                                   │
#  │     CRITICAL은 항상 재생, NORMAL만 큐 2개 초과 시 스킵                  │
#  └─────────────────────────────────────────────────────────────────────────┘
# ══════════════════════════════════════════════════════════════════════════════

class _SoundEngine:
    """플랫폼 독립 사운드 엔진. pygame ▶ winsound ▶ 무음 순서로 폴백."""

    CRITICAL = 0   # 포획·시작·완료 — 스킵 불가
    NORMAL   = 1   # 카운트다운 틱  — 큐 혼잡 시 스킵 허용

    _SAMPLE_RATE = 44100
    _VOLUME      = 0.72
    _NORMAL_MAX  = 2     # NORMAL 항목이 이 수 이상이면 새 NORMAL 스킵

    def __init__(self):
        self._backend  = self._detect_backend()
        self._pq: _queue_mod.PriorityQueue = _queue_mod.PriorityQueue()
        self._seq       = 0          # 동일 우선순위 내 FIFO 보장용 시퀀스
        self._seq_lock  = threading.Lock()
        self._cache: Dict[Tuple[int,int], bytes] = {}  # (freq,dur) → raw PCM
        # v1.9.6: pygame Sound 객체도 캐싱 (PCM은 캐시되지만 Sound는 매번 신규 → GC 부담)
        # 같은 (freq, dur_ms) 비프는 캐시된 Sound 인스턴스 재사용
        self._sound_cache: Dict[Tuple[int,int], object] = {}
        self._enabled   = True

        # v1.7: NORMAL 항목 수를 별도 카운터로 추적 (큐 내부 접근 X)
        # _pq.queue 직접 탐색은 deque thread-safety 보장 X → 카운터 + Lock으로 교체
        self._normal_count = 0
        self._normal_lock  = threading.Lock()

        self._worker = threading.Thread(target=self._run, daemon=True)
        self._worker.start()

    # ── 백엔드 감지 ───────────────────────────────────────────────────────────
    def _detect_backend(self) -> str:
        try:
            import pygame
            pygame.mixer.pre_init(
                frequency=self._SAMPLE_RATE, size=-16,
                channels=1, buffer=512,
            )
            pygame.mixer.init()
            self._pygame = pygame
            log.info("사운드 백엔드: pygame")
            return 'pygame'
        except Exception as e:
            log.debug(f"pygame 백엔드 초기화 실패: {e}")

        try:
            import winsound as _ws
            self._winsound = _ws
            log.info("사운드 백엔드: winsound")
            return 'winsound'
        except ImportError:
            log.debug("winsound 없음 (Windows 전용)")

        log.warning("사운드 백엔드 없음 → 무음 모드")
        return 'silent'

    # ── 사인파 합성 (numpy 불필요) ────────────────────────────────────────────
    def _synthesize(self, freq: int, dur_ms: int) -> bytes:
        """freq Hz · dur_ms 밀리초의 PCM 16-bit mono 사인파를 반환한다."""
        key = (freq, dur_ms)
        if key in self._cache:
            return self._cache[key]

        rate  = self._SAMPLE_RATE
        n     = int(rate * dur_ms / 1000)
        fade  = max(1, int(rate * 0.012))   # 12ms 페이드아웃 (클릭 잡음 방지)
        vol   = self._VOLUME
        omega = 2 * math.pi * freq / rate
        buf   = bytearray(n * 2)

        for i in range(n):
            val = int(32767 * vol * math.sin(omega * i))
            if i > n - fade:
                val = int(val * (n - i) / fade)
            struct.pack_into('<h', buf, i * 2, max(-32767, min(32767, val)))

        raw = bytes(buf)
        self._cache[key] = raw
        return raw

    # ── 공개 API ──────────────────────────────────────────────────────────────
    def play(self, beep_list: List[Tuple[int, int]],
             priority: int = NORMAL):
        """
        beep_list: [(freq, dur_ms), ...]  순서대로 재생.
        priority : CRITICAL(0) 또는 NORMAL(1).
        """
        if not self._enabled or self._backend == 'silent':
            return

        # NORMAL은 큐 혼잡 시 스킵 (v1.7: 큐 내부 직접 탐색 → 카운터로 교체)
        if priority == self.NORMAL:
            with self._normal_lock:
                if self._normal_count >= self._NORMAL_MAX:
                    return
                self._normal_count += 1

        with self._seq_lock:
            self._seq += 1
            seq = self._seq

        self._pq.put((priority, seq, beep_list))

    def set_enabled(self, value: bool):
        self._enabled = value

    def shutdown(self):
        """앱 종료 시 워커 스레드를 안전하게 멈춘다."""
        self._pq.put((self.CRITICAL, -1, None))   # sentinel

    # ── 워커 스레드 ───────────────────────────────────────────────────────────
    def _run(self):
        while True:
            priority, seq, beep_list = self._pq.get()
            if beep_list is None:   # shutdown sentinel
                break
            try:
                self._play_beep_list(beep_list)
            except Exception as e:
                log.warning(f"사운드 재생 실패: {e}")
            finally:
                # v1.7: NORMAL 재생 완료 시 카운터 감소
                if priority == self.NORMAL:
                    with self._normal_lock:
                        self._normal_count = max(0, self._normal_count - 1)
            self._pq.task_done()

    def _play_beep_list(self, beep_list: List[Tuple[int, int]]):
        if self._backend == 'pygame':
            self._play_pygame(beep_list)
        elif self._backend == 'winsound':
            self._play_winsound(beep_list)

    def _play_pygame(self, beep_list: List[Tuple[int, int]]):
        # v1.9.6: 모듈 레벨 time import 사용 (재import 제거)
        pygame = self._pygame
        cache  = self._sound_cache
        for freq, dur in beep_list:
            freq = max(20, min(20000, freq))
            dur  = max(10, dur)
            key  = (freq, dur)
            snd  = cache.get(key)
            if snd is None:
                # PCM 합성 후 Sound 인스턴스 만들어 캐시
                raw       = self._synthesize(freq, dur)
                snd       = pygame.mixer.Sound(buffer=raw)
                cache[key] = snd
            snd.play()
            time.sleep(dur / 1000)

    def _play_winsound(self, beep_list: List[Tuple[int, int]]):
        ws = self._winsound
        for freq, dur in beep_list:
            ws.Beep(max(37, min(32767, freq)), max(10, dur))

    # ── 백엔드 이름 (디버그용) ────────────────────────────────────────────────
    @property
    def backend(self) -> str:
        return self._backend


# 전역 싱글턴 (모듈 로드 시 한 번만 초기화)
_sound_engine = _SoundEngine()


