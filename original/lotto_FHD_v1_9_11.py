# 7.  LottoSelfTest  –  공정성 헤드리스 검증 (v1.9.9, tkinter 없음)
#
#  "순수성 선언"을 데이터로 증명한다.
#  GUI·소리·sleep 없이 LottoEngine 만 고속 구동해 수만 게임을 돌리고,
#  번호 출현 분포·구멍 편향을 카이제곱 적합도 검정으로 평가한다.
#
#  매 프레임 물리 시퀀스는 LottoMachine._animate() 와 동일하게 재현:
#     apply_magnet → move_balls → check_collisions → check_hole
#  가속도 라이브와 같은 주기(ACCEL_INTERVAL)로 accelerate_balls() 호출.
#
#  통계 주의
#  ┌─────────────────────────────────────────────────────────────────────────┐
#  │  한 게임의 6개 번호는 비복원 추출이라 서로 음(−)의 상관 (독립 아님).    │
#  │  → 6개 풀 카이제곱은 근사(보수적) 검정.                                  │
#  │    게임 간 완전 독립인 "첫 번째 캡처 공" 분포가 더 엄격한 균등성 검정.   │
#  │  p-value 는 Wilson–Hilferty 정규근사(math.erfc) — 외부 의존성 0.        │
#  └─────────────────────────────────────────────────────────────────────────┘
# ══════════════════════════════════════════════════════════════════════════════

# 카이제곱 상위꼬리 임계값 (유의수준별). 자가검증에 쓰는 자유도만 수록.
_CHI2_CRIT: Dict[int, Dict[float, float]] = {
    1:  {0.05: 3.841,  0.01: 6.635,  0.001: 10.828},   # 구멍 2개 (df = k−1 = 1)
    3:  {0.05: 7.815,  0.01: 11.345, 0.001: 16.266},   # 구멍 4개 (df = 3)
    44: {0.05: 60.481, 0.01: 68.710, 0.001: 78.750},   # 번호 45개 (df = 44)
}


def _chi_square(observed: List[float], expected: float) -> float:
    """단일 기대값(균등 가정)에 대한 카이제곱 적합도 통계량 Σ(O−E)²/E."""
    if expected <= 0:
        return 0.0
    return sum((o - expected) ** 2 / expected for o in observed)


def _chi_square_pvalue(chi2: float, df: int) -> float:
    """카이제곱 상위꼬리 p-value 근사 (Wilson–Hilferty).

    P(χ²_df ≥ chi2) ≈ 0.5·erfc(z/√2).  자유도 30+ 에서 매우 정확,
    작은 자유도(구멍 검정)에선 임계값 비교를 함께 볼 것."""
    if df <= 0 or chi2 <= 0:
        return 1.0
    t = 2.0 / (9.0 * df)
    z = ((chi2 / df) ** (1.0 / 3.0) - (1.0 - t)) / math.sqrt(t)
    return 0.5 * math.erfc(z / math.sqrt(2.0))


def _verdict(chi2: float, df: int) -> str:
    """카이제곱 통계량 → 사람이 읽을 판정 문자열."""
    crit = _CHI2_CRIT.get(df)
    if crit is None:
        return "판정표 없음"
    if chi2 < crit[0.05]:
        return "✅ 균등 분포와 통계적으로 구분되지 않음 (편향 근거 없음)"
    if chi2 < crit[0.01]:
        return "🟡 약한 이탈 (α=0.05 초과, 0.01 이내) — 표본 더 늘려 재확인"
    if chi2 < crit[0.001]:
        return "🟠 유의한 이탈 (α=0.01 초과) — 편향 의심"
    return "🔴 매우 강한 이탈 (α=0.001 초과) — 편향 가능성 높음"


_HOLE_LABEL = {0: '좌상', 1: '우상', 2: '좌하', 3: '우하'}


class LottoSelfTest:
    """LottoEngine 을 헤드리스로 구동해 공정성을 통계 검증한다 (tkinter 없음)."""

    # 라이브 _animate 가 ACCEL_INTERVAL(ms)마다 accelerate 하는 것을 프레임 수로 환산
    _ACCEL_EVERY = max(1, round(ACCEL_INTERVAL / FRAME_MS))
    # 한 게임이 이 프레임 수를 넘으면 타임아웃 (물리상 도달 불가 — 방어용)
    _MAX_FRAMES_PER_DRAW = 200_000

    def __init__(self, hole_count: int = 1):
        self.engine = LottoEngine(hole_count=hole_count)

    # ── 게임 1회를 헤드리스로 구동 ────────────────────────────────────────────
    def _run_one_draw(self) -> Tuple[List[int], List[int], bool, int]:
        """공 1세트가 구멍에 다 빨려들어갈 때까지 시뮬레이션.

        반환: (캡처순 번호 리스트, 같은 순서의 캡처 구멍 인덱스, 타임아웃, 프레임 수)
        """
        eng = self.engine
        eng.reset_draw()          # target_speed 초기화 + 공/번호 비움
        eng.create_all_balls()    # 1~45 새로 생성 (순서 셔플)
        holes = eng.active_holes
        capturing: List[int] = []

        frame = 0
        timed_out = False
        while len(eng.drawn_numbers) < 6:
            # 라이브와 동일 주기로 목표속도 상승 (첫 가속은 _ACCEL_EVERY 프레임째)
            if frame > 0 and frame % self._ACCEL_EVERY == 0:
                eng.accelerate_balls()
            # _animate() 의 RUNNING 분기와 동일한 물리 시퀀스
            eng.apply_magnet()
            eng.move_balls()
            eng.check_collisions()
            captured = eng.check_hole()
            if captured is not None:
                # check_hole 은 어느 구멍인지 안 알려주므로 최근접 구멍으로 식별.
                # (구멍 간 거리 ≥ 960px, 캡처 반경 4px → 모호성 없음)
                best_i, best_d = 0, float('inf')
                for i, (hx, hy) in enumerate(holes):
                    d = (captured.x - hx) ** 2 + (captured.y - hy) ** 2
                    if d < best_d:
                        best_d, best_i = d, i
                capturing.append(best_i)
            frame += 1
            if frame >= self._MAX_FRAMES_PER_DRAW:
                timed_out = True
                break

        return list(eng.drawn_numbers), capturing, timed_out, frame

    # ── N회 구동 + 통계 집계 ──────────────────────────────────────────────────
    def run(self, n_draws: int, detail: bool = False) -> dict:
        """n_draws 회 구동하고 콘솔 리포트를 출력한 뒤 결과 dict 반환."""
        num_holes  = len(self.engine.active_holes)
        freq_all   = {k: 0 for k in range(1, 46)}   # 당첨 6개 전체 풀
        freq_first = {k: 0 for k in range(1, 46)}   # 첫 캡처 공만 (독립표본)
        hole_cap   = [0] * num_holes
        frames_sum = 0
        timeouts   = 0
        valid      = 0

        mode_label = {1: '구멍1', 2: '구멍2', 4: '구멍4'}.get(
            self.engine.hole_count, f'구멍{self.engine.hole_count}')
        step = max(1, n_draws // 20)   # 진행률 약 5%마다 갱신

        t0 = time.perf_counter()
        for i in range(1, n_draws + 1):
            nums, holes, timed_out, frames = self._run_one_draw()
            if timed_out or len(nums) < 6:
                timeouts += 1
            else:
                valid      += 1
                frames_sum += frames
                for x in nums:
                    freq_all[x] += 1
                freq_first[nums[0]] += 1
                for hi in holes:
                    hole_cap[hi] += 1
            # 진행률 — stdout 리포트를 더럽히지 않게 stderr 로, 한 줄 덮어쓰기
            if i % step == 0 or i == n_draws:
                el  = time.perf_counter() - t0
                rate = i / el if el > 0 else 0.0
                eta  = (n_draws - i) / rate if rate > 0 else 0.0
                print(f"\r  [{mode_label}] {i:,}/{n_draws:,} "
                      f"({100.0*i/n_draws:4.0f}%)  {rate:,.0f}게임/초  "
                      f"남은시간 ~{eta:4.0f}초   ",
                      end='', file=sys.stderr, flush=True)
        print("\r" + " " * 70 + "\r", end='', file=sys.stderr, flush=True)
        elapsed = time.perf_counter() - t0

        self._print_report(self.engine.hole_count, num_holes, n_draws, valid,
                           timeouts, elapsed, freq_all, freq_first, hole_cap,
                           frames_sum, detail)
        return {
            'hole_count': self.engine.hole_count, 'n_draws': n_draws,
            'valid': valid, 'timeouts': timeouts, 'elapsed': elapsed,
            'freq_all': freq_all, 'freq_first': freq_first,
            'hole_capture': hole_cap,
        }

    # ── 리포트 ────────────────────────────────────────────────────────────────
    def _print_dist(self, title: str, freq: Dict[int, int],
                    expected: float, df: int, note: str = ''):
        counts = list(freq.values())
        mean = sum(counts) / len(counts)
        std  = (sum((c - mean) ** 2 for c in counts) / len(counts)) ** 0.5
        mn_k = min(freq, key=freq.get)
        mx_k = max(freq, key=freq.get)
        chi2 = _chi_square([float(c) for c in counts], expected)
        p    = _chi_square_pvalue(chi2, df)
        crit = _CHI2_CRIT.get(df, {})

        print(f"  ── {title} ─────────────")
        if note:
            print(f"     · {note}")
        print(f"     기대값  : 번호당 {expected:,.1f} 회")
        print(f"     실측    : 최소 {freq[mn_k]:,} ({mn_k}번) · "
              f"최대 {freq[mx_k]:,} ({mx_k}번) · 평균 {mean:,.1f} · 표준편차 {std:.1f}")
        print(f"     카이제곱: χ² = {chi2:.2f}   (자유도 {df})")
        if crit:
            print(f"     임계값  : {crit[0.05]:.1f} (α=0.05) · {crit[0.01]:.1f} (α=0.01)")
        print(f"     근사 p  : {p:.3g}   (Wilson–Hilferty)")
        print(f"     판정    : {_verdict(chi2, df)}")
        print()

    def _print_report(self, hc, num_holes, n_draws, valid, timeouts, elapsed,
                      freq_all, freq_first, hole_cap, frames_sum, detail):
        bar  = "═" * 66
        mode = {1: "1개 (우상)",
                2: "2개 (우상+좌하 대각 대칭)",
                4: "4개 (네 모서리)"}.get(hc, str(hc))
        dps        = (n_draws / elapsed) if elapsed > 0 else 0.0
        avg_frames = (frames_sum / valid) if valid else 0.0
        sim_sec    = avg_frames * FRAME_MS / 1000.0

        print()
        print(bar)
        print(f"  로또추첨기 공정성 자가검증   ·   구멍 {mode}   (v{APP_VERSION})")
        print(bar)
        print(f"  표본    : {n_draws:,} 게임 요청 · {valid:,} 유효 · 타임아웃 {timeouts:,}")
        print(f"  소요    : {elapsed:.1f}초 · {dps:,.0f} 게임/초 · "
              f"평균 {avg_frames:,.0f} 프레임/게임 (시뮬 {sim_sec:.1f}초)")
        print(bar)

        if valid == 0:
            print("  ⚠ 유효 게임 0 — 물리가 캡처에 실패(타임아웃). 검증 불가.")
            print(bar)
            print()
            return

        # ① 6개 전체 풀 (근사 검정)
        self._print_dist(
            "번호 출현 분포 (당첨 6개 전체)", freq_all, valid * 6 / 45.0, 44,
            note="6개는 비복원 추출 → 음의 상관, 근사(보수적) 검정")
        # ② 첫 캡처 공 (독립표본 — 더 엄격)
        self._print_dist(
            "첫 번째로 빠진 공 분포 (게임 간 독립 · 엄격)", freq_first,
            valid / 45.0, 44,
            note="게임마다 1개만 집계 → 완전 독립 i.i.d. 균등성 검정")

        # ③ 구멍별 캡처 분포 (위치 편향)
        if num_holes > 1:
            total_cap = sum(hole_cap)
            exp_h = total_cap / num_holes if num_holes else 0.0
            df_h  = num_holes - 1
            chi2  = _chi_square([float(c) for c in hole_cap], exp_h)
            p     = _chi_square_pvalue(chi2, df_h)
            crit  = _CHI2_CRIT.get(df_h, {})
            print("  ── 구멍별 캡처 분포 (위치·모서리 편향 검사) ─────────────")
            for i, c in enumerate(hole_cap):
                pct = (100.0 * c / total_cap) if total_cap else 0.0
                print(f"     구멍 {i} ({_HOLE_LABEL.get(i, '?')}) : "
                      f"{c:>9,} 회  ({pct:5.2f}%)")
            print(f"     기대값  : 구멍당 {exp_h:,.1f} 회")
            print(f"     카이제곱: χ² = {chi2:.2f}   (자유도 {df_h})")
            if crit:
                print(f"     임계값  : {crit[0.05]:.1f} (α=0.05) · "
                      f"{crit[0.01]:.1f} (α=0.01)")
            print(f"     근사 p  : {p:.3g}")
            print(f"     판정    : {_verdict(chi2, df_h)}")
            print()
        else:
            print("  ── 구멍별 캡처 분포 ─────────────────────────────────────")
            print("     1개(우상) 모드 — 전 게임 동일 구멍, 위치 편향 검사 해당 없음")
            print()

        # ④ 번호별 상세 표 (--detail)
        if detail:
            print("  ── 번호별 출현 횟수 (1~45) ──────────────────────────────")
            cells = [f"{k:2d}:{freq_all[k]:>6,}" for k in range(1, 46)]
            for r in range(0, 45, 9):
                print("     " + "  ".join(cells[r:r + 9]))
            print()

        print(bar)
        print()


